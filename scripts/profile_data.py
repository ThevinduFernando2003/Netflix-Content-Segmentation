"""Profile the raw catalogue and write reports/data_profile.md.

Every count in the report is computed here. Re-run this script to refresh it.
"""

from __future__ import annotations

import os
import sys
from collections import Counter
from pathlib import Path

os.environ.setdefault("OMP_NUM_THREADS", "1")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from _common import markdown_table, prepare, reports_dir  # noqa: E402
from config import project_path  # noqa: E402
from data.clean import (  # noqa: E402
    RATING_DURATION_RE,
    clean_dataframe,
    date_formats,
    listwise_deletion_count,
    missing_tokens,
    parse_date_added,
)
from data.load import load_titles  # noqa: E402


def main() -> None:
    config = prepare()
    frame = load_titles(project_path(config, "raw_csv"))
    tokens = missing_tokens(config)
    cleaned = clean_dataframe(frame, config)
    deletion = listwise_deletion_count(frame, config)
    dates, date_failures = parse_date_added(frame["date_added"], date_formats(config), tokens)
    rating_text = frame["rating"].astype("string")
    contaminated = int(rating_text.str.match(RATING_DURATION_RE, na=False).sum())
    duration_failures = int(
        (
            cleaned["duration"].notna()
            & cleaned["duration_minutes"].isna()
            & cleaned["duration_seasons"].isna()
        ).sum()
    )
    genre_counts: Counter[str] = Counter()
    for genres in cleaned["genre_list"]:
        genre_counts.update(genres)

    lines = [
        "# Data profile",
        "",
        "Generated by `scripts/profile_data.py`. Re-run that script to refresh every number.",
        "",
        "## Contract versus the file on disk",
        "",
        "The brief describes the public Netflix titles dump (`cast`, `description`, "
        "about 8,791 rows, dates like `September 25, 2021`). **This file wins where they disagree.**",
        "",
        f"- Rows: **{len(frame)}**. Columns: `{list(frame.columns)}`.",
        "- `cast` and `description` are **absent**. The loader adds empty strings. "
        "The text block is therefore the title only.",
        "- Missing director and country are the literal token `not given`, not nulls.",
        "- `date_added` is `M/D/YYYY` (and was mixed with Excel datetimes before the CSV export).",
        f"- Rating values matching `^\\d+\\s*min$`: **{contaminated}**. The cleaner still handles that defect.",
        "",
        "## Shape and types",
        "",
        markdown_table(
            ["column", "dtype", "nulls", "null_pct"],
            [
                [
                    column,
                    str(frame[column].dtype),
                    int(frame[column].isna().sum()),
                    100.0 * float(frame[column].isna().mean()),
                ]
                for column in frame.columns
            ],
        ),
        "",
        f"Duplicate `show_id` values: **{int(frame['show_id'].duplicated().sum())}**.",
        "",
        "## Type",
        "",
        markdown_table(
            ["type", "count"],
            [
                [str(key), int(value)]
                for key, value in frame["type"].value_counts(dropna=False).items()
            ],
        ),
        "",
        "## Rating",
        "",
        markdown_table(
            ["rating", "count"],
            [
                [str(key), int(value)]
                for key, value in frame["rating"].value_counts(dropna=False).items()
            ],
        ),
        "",
        "## Missingness after treating `not given` as missing",
        "",
        "Listwise deletion on director, country, date, rating, duration, listed_in and title "
        f"would drop **{deletion['listwise_partial_fields']}** of {deletion['rows']} rows "
        f"({100.0 * deletion['listwise_partial_fields'] / deletion['rows']:.1f}%). "
        "That is mostly missing directors. Those rows are imputed / indicated, not dropped.",
        "",
        "If the absent `cast` and `description` columns are also treated as missing, listwise deletion "
        f"drops **{deletion['listwise_including_cast_and_description']}** rows. "
        "They are filled with empty strings instead.",
        "",
        markdown_table(
            ["field", "missing_rows"],
            [
                [field, deletion[f"missing_{field}"]]
                for field in [
                    "director",
                    "cast",
                    "country",
                    "date_added",
                    "rating",
                    "duration",
                    "listed_in",
                    "description",
                ]
            ],
        ),
        "",
        "## Duration",
        "",
        f"Parsed minutes: **{int(cleaned['duration_minutes'].notna().sum())}**. "
        f"Parsed seasons: **{int(cleaned['duration_seasons'].notna().sum())}**. "
        f"Unparsed non-missing durations: **{duration_failures}**.",
        "",
        "Clustering uses `duration_normalised` (within-type percentile), not both raw units. "
        "See `docs/DECISIONS.md`.",
        "",
        "## date_added",
        "",
        f"Parse failures under the explicit format list: **{date_failures}**. "
        f"Successfully parsed: **{int(dates.notna().sum())}**.",
        "",
        "## Release year",
        "",
        markdown_table(
            ["stat", "value"],
            [
                ["min", int(frame["release_year"].min())],
                ["p25", float(frame["release_year"].quantile(0.25))],
                ["median", float(frame["release_year"].median())],
                ["p75", float(frame["release_year"].quantile(0.75))],
                ["max", int(frame["release_year"].max())],
                ["mean", float(frame["release_year"].mean())],
            ],
        ),
        "",
        "## Genre vocabulary",
        "",
        f"Distinct genres after splitting `listed_in`: **{len(genre_counts)}**.",
        "",
        markdown_table(
            ["genre", "count"],
            [[genre, count] for genre, count in genre_counts.most_common()],
        ),
        "",
    ]
    target = reports_dir(config) / "data_profile.md"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {target}")


if __name__ == "__main__":
    main()
